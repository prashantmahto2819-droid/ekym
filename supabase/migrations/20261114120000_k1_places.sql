/** The official English state for any spelling; null when it is not an Indian state / UT. */
create or replace function public.k1_canon_state(p text) returns text
language sql stable parallel safe set search_path = '' as $$
  with k as (select public.k1_place_key(p) k)
  select coalesce(
    (select s.state from public.k1_places s, k where s.district is null and (public.k1_place_key(s.state) = k.k or public.k1_place_key(s.state_hi) = k.k) limit 1),
    (select a.state from public.k1_place_aliases a, k where a.key = k.k and a.district is null))
  where (select k from k) <> ''
$$;

/** Official state + district for what was typed; unknown values come back as typed (trimmed). */
create or replace function public.k1_canon_place(p_state text, p_district text, out state text, out district text)
language plpgsql stable set search_path = '' as $$
declare
  st text := public.k1_canon_state(p_state);
  dk text := public.k1_place_key(regexp_replace(coalesce(p_district, ''), '\s*(district|distt\.?|dist\.?|ज़िला|जिला)\s*$', '', 'i'));
  hit record; n int;
begin
  state := coalesce(st, nullif(btrim(p_state), ''), p_state);
  district := coalesce(nullif(regexp_replace(btrim(p_district), '\s+', ' ', 'g'), ''), p_district);
  if dk = '' then return; end if;
  select a.state, a.district into hit from public.k1_place_aliases a where a.key = dk and a.district is not null and (st is null or a.state = st);
  if found then district := hit.district; if st is null then state := hit.state; end if; return; end if;
  select count(*) into n from public.k1_places p
   where p.district is not null and (st is null or p.state = st)
     and dk in (public.k1_place_key(p.district), public.k1_place_key(p.district_hi), public.k1_place_key(regexp_replace(p.district, '\s*\(.*\)', '')));
  if n = 1 then
    select p.state, p.district into hit from public.k1_places p
     where p.district is not null and (st is null or p.state = st)
       and dk in (public.k1_place_key(p.district), public.k1_place_key(p.district_hi), public.k1_place_key(regexp_replace(p.district, '\s*\(.*\)', '')));
    district := hit.district;
    if st is null and nullif(btrim(p_state), '') is null then state := hit.state; end if;
  end if;
end $$;

create or replace function public.k1_places_canon() returns trigger
language plpgsql set search_path = '' as $$
declare j jsonb := to_jsonb(new); c record;
begin
  select * into c from public.k1_canon_place(j->>'state', j->>'district');
  new := jsonb_populate_record(new, jsonb_strip_nulls(jsonb_build_object(
    'state', case when j ? 'state' then c.state end,
    'district', case when j ? 'district' then c.district end)));
  return new;
end $$;

