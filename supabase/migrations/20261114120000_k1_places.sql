-- Places done right (Nov 2026): one reference list of states / UTs and their districts (English + Hindi), and every
-- Kalchuri form table stores the official English spelling whatever was typed — Hindi, old names (Orissa, Pondicherry,
-- Kawardha), India Post spellings (Chattisgarh), short forms (CG, MP), any case. Unknown names are kept as typed.
-- Same rules as src/lib/places.ts (canonState / canonDistrict). Additive; existing rows are corrected once below.

create table if not exists public.k1_places (
  id bigint generated always as identity primary key,
  state text not null,
  state_hi text,
  district text,          -- null = the state's own row
  district_hi text,
  unique nulls not distinct (state, district)
);
alter table public.k1_places enable row level security;
drop policy if exists k1_places_read on public.k1_places;
create policy k1_places_read on public.k1_places for select to anon, authenticated using (true);
grant select on public.k1_places to anon, authenticated;

create table if not exists public.k1_place_aliases (
  key text primary key,   -- k1_place_key() of the other name
  state text not null,
  district text           -- null = a state alias
);
alter table public.k1_place_aliases enable row level security;
drop policy if exists k1_place_aliases_read on public.k1_place_aliases;
create policy k1_place_aliases_read on public.k1_place_aliases for select to anon, authenticated using (true);
grant select on public.k1_place_aliases to anon, authenticated;

